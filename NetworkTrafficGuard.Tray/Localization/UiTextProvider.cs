    public static UiText Get(string? cultureName)
    {
        var culture = SupportedCultures.GetCultureOrDefault(cultureName).Name;

        return culture switch
        {
            SupportedCultures.SimplifiedChinese => SimplifiedChinese,
            SupportedCultures.Japanese => Japanese,
            SupportedCultures.English => English,
            _ => TraditionalChinese
        };
    }

